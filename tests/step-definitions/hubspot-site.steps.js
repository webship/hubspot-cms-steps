'use strict';

// Step definitions for what a HubSpot CMS page says about itself and the
// HubSpot features a page loads.
//
// What these steps rely on, all checked on public sites built on HubSpot CMS:
//
//   - `<meta name="generator" content="HubSpot">`, which every page carries
//   - the body classes HubSpot's `builtin_body_classes` adds (sometimes to a
//     wrapper element instead of the `body`): `hs-site-page`, `hs-landing-page`,
//     `hs-blog-listing`, `hs-blog-post`, plus `hs-content-id-<id>` and
//     `hs-content-path-<path>`
//   - the tracking code: `script#hs-script-loader`, whose address ends in
//     `/hs/scriptloader/<portal id>.js` (or `js.hs-scripts.com/<portal id>.js`)
//   - the chat widget: `#hubspot-messages-iframe-container`, added by script
//   - the meetings embed: `.meetings-iframe-container` holding an iframe
//   - translations: `link[rel="alternate"][hreflang]` in the head, and the
//     language switcher module, `.lang_switcher_class`
//   - `link[rel="canonical"]` and `meta[name="robots"]`
//
// The product word is optional ("the HubSpot page" and "the page" both match).

const { When, Then } = require('@cucumber/cucumber');
const { friendly, smartSettle } = require('webship-js/tests/step-definitions/webship');
const { budget, escapeRegExp, sameAddress, actOrExplain, poll } = require('./hubspot-helpers');

const TRACKING_SCRIPT = '#hs-script-loader, script[src*="hs-scripts.com"], script[src*="/hs/scriptloader/"]';
const CHAT_CONTAINER = '#hubspot-messages-iframe-container';
const LANGUAGE_SWITCHER = '.lang_switcher_class, .hs_cos_wrapper_type_language_switcher';

const PAGE_KINDS = {
  website: { selector: '.hs-site-page', label: 'website page' },
  landing: { selector: '.hs-landing-page', label: 'landing page' },
  'blog listing': { selector: '.hs-blog-listing', label: 'blog listing page' },
  'blog post': { selector: '.hs-blog-post', label: 'blog post page' },
};

/**
 * Assert the page is (or is not) of a HubSpot kind: a website page, a landing
 * page, a blog listing page or a blog post page. HubSpot marks each with a
 * class (`hs-site-page`, `hs-landing-page`, `hs-blog-listing`, `hs-blog-post`)
 * on the body, whatever the theme.
 *
 * Example #1: Then the page should be a HubSpot website page
 * Example #2: Then the page should be a HubSpot landing page
 * Example #3: And the page should be a HubSpot blog listing page
 * Example #4: And this page should be a HubSpot blog post page
 * Example #5: But the page should not be a HubSpot blog post page
 *
 */
Then(/^(?:the |this )?page should( not)* be a HubSpot (website|landing|blog listing|blog post) page$/, async function (notCase, kind) {
  const { selector, label } = PAGE_KINDS[kind];
  const timeout = budget(this);
  const found = await poll(this, async () => ((await this.page.locator(selector).count()) > 0) === !notCase, timeout);
  if (!found) {
    const classes = await this.page.evaluate(() => Array.from(document.querySelectorAll('[class*="hs-"]'))
      .flatMap((n) => Array.from(n.classList)).filter((c) => /^hs-(site-page|landing-page|blog-listing|blog-post|content-path)/.test(c)).slice(0, 4)).catch(() => []);
    throw friendly({
      message: notCase
        ? `Expected the page not to be a HubSpot ${label}, but it carries \`${selector}\`.`
        : `Expected the page to be a HubSpot ${label} (\`${selector}\`), found ${classes.length ? classes.map((c) => `\`${c}\``).join(', ') : 'no HubSpot page class'}.`,
      hint: 'HubSpot adds `hs-site-page`, `hs-landing-page`, `hs-blog-listing` or `hs-blog-post` through the `builtin_body_classes` variable; a theme that leaves it out has none of them.',
    });
  }
});

/**
 * Assert that the current page was (or was not) generated by HubSpot, via
 * the `<meta name="generator" content="HubSpot">` tag HubSpot CMS pages
 * emit.
 *
 * Example #1: Then the page should be a HubSpot page
 * Example #2: And the page should be a HubSpot page
 * Example #3: Then this page should be a HubSpot page
 * Example #4: But the page should not be a HubSpot page
 * Example #5: Then page should be a HubSpot page
 *
 */
Then(/^(?:the |this )?page should( not)* be a HubSpot page$/, async function (notCase) {
  const timeout = budget(this);
  try {
    await this.page.waitForFunction((want) => {
      const meta = document.querySelector('meta[name="generator"]');
      const content = meta ? (meta.getAttribute('content') || '') : '';
      return content.toLowerCase().includes('hubspot') === want;
    }, !notCase, { timeout });
  } catch {
    const content = await this.page.locator('meta[name="generator"]').first().getAttribute('content').catch(() => null);
    throw friendly({
      message: notCase
        ? `Expected the page not to be a HubSpot page, but its generator meta tag is "${content}".`
        : `Expected a <meta name="generator" content="HubSpot"> tag, found: ${content === null ? 'no generator meta tag' : `"${content}"`}.`,
      hint: 'HubSpot CMS writes the generator meta tag into every hosted page; a page served from another host or a proxy error page will not carry it.',
    });
  }
});

/**
 * Assert the HubSpot tracking code is (or is not) installed on the page,
 * optionally for the given portal (account) id. The tracking code is
 * `script#hs-script-loader`, whose address ends in `<portal id>.js`.
 *
 * Example #1: Then the HubSpot tracking code should be installed
 * Example #2: And the HubSpot tracking code should be installed for portal "213255"
 * Example #3: Then the tracking code should be installed
 * Example #4: But the HubSpot tracking code should not be installed
 * Example #5: Then the tracking code should be installed for portal "0000000"
 *
 */
Then(/^(?:the )?(?:HubSpot )?tracking code should( not)* be installed(?: for portal "(\d+)")?$/, async function (notCase, portal) {
  const scripts = this.page.locator(TRACKING_SCRIPT);
  let sources = [];
  const ok = await poll(this, async () => {
    sources = await scripts.evaluateAll((nodes) => nodes.map((n) => n.getAttribute('src') || ''));
    const hit = portal ? sources.some((src) => new RegExp(`/${escapeRegExp(portal)}\\.js(\\?|$)`).test(src)) : sources.length > 0;
    return hit === !notCase;
  });
  if (!ok) {
    throw friendly({
      message: notCase
        ? `Expected the HubSpot tracking code not to be installed${portal ? ` for portal ${portal}` : ''}, but it is.`
        : `Expected the HubSpot tracking code to be installed${portal ? ` for portal ${portal}` : ''}, found ${sources.length ? `"${sources.join('", "')}"` : 'no tracking script'}.`,
      hint: 'The tracking code is `script#hs-script-loader` (`/hs/scriptloader/<portal id>.js` or `js.hs-scripts.com/<portal id>.js`); it is added by `standard_header_includes` and by the tracking code setting of the account. The portal id is in the HubSpot account settings.',
    });
  }
});

/**
 * Assert the HubSpot chat widget is (or is not) on the page: its container
 * `#hubspot-messages-iframe-container`, which the chat script adds. "Present"
 * means in the page; "visible" means shown to the visitor.
 *
 * Example #1: Then the HubSpot chat widget should be present
 * Example #2: And the chat widget should be visible
 * Example #3: Then the HubSpot chat widget should be visible
 * Example #4: But the chat widget should not be present
 * Example #5: Then chat widget should be present
 *
 */
Then(/^(?:the )?(?:HubSpot )?chat widget should( not)* be (present|visible)$/, async function (notCase, state) {
  const container = this.page.locator(CHAT_CONTAINER).first();
  const ok = await poll(this, async () => {
    const present = (await this.page.locator(CHAT_CONTAINER).count()) > 0;
    const here = state === 'visible' ? present && await container.isVisible().catch(() => false) : present;
    return here === !notCase;
  });
  if (!ok) {
    throw friendly({
      message: notCase ? `Expected the HubSpot chat widget not to be ${state}, but it is.` : `Expected the HubSpot chat widget to be ${state} (\`${CHAT_CONTAINER}\`) within ${budget(this)} ms, but it is not.`,
      hint: 'The chat script adds `#hubspot-messages-iframe-container` after the page loads, and only when a chatflow is published for the page and the visitor has answered the cookie banner where consent is required.',
    });
  }
});

/**
 * Assert the page does (or does not) have a HubSpot meetings embed: the
 * `.meetings-iframe-container` with its iframe, optionally for a meetings link
 * (the part of the address after the host, such as "/meetings/jane").
 *
 * Example #1: Then the page should have a HubSpot meetings embed
 * Example #2: And the page should have a HubSpot meetings embed for "/meetings/setup/head-of-growth-call"
 * Example #3: Then this page should have a HubSpot meetings embed
 * Example #4: But the page should not have a HubSpot meetings embed
 * Example #5: Then page should have a HubSpot meetings embed for "/meetings/jane"
 *
 */
Then(/^(?:the |this )?page should( not)* have a (?:HubSpot )?meetings embed(?: for "([^"]*)")?$/, async function (notCase, link) {
  const frames = this.page.locator('.meetings-iframe-container iframe');
  let sources = [];
  const ok = await poll(this, async () => {
    sources = await frames.evaluateAll((nodes) => nodes.map((n) => n.getAttribute('src') || ''));
    const hit = link ? sources.some((src) => src.includes(link)) : sources.length > 0;
    return hit === !notCase;
  });
  if (!ok) {
    throw friendly({
      message: notCase
        ? `Expected the page not to have a HubSpot meetings embed${link ? ` for "${link}"` : ''}, but it has one.`
        : `Expected the page to have a HubSpot meetings embed${link ? ` for "${link}"` : ''}, found ${sources.length ? `"${sources.join('", "')}"` : 'none'}.`,
      hint: 'The meetings embed is an iframe inside `.meetings-iframe-container`; its address is the meetings link of the account.',
    });
  }
});

/**
 * Assert the page does (or does not) have a language switcher: the language
 * switcher module (`.lang_switcher_class`).
 *
 * Example #1: Then the page should have a HubSpot language switcher
 * Example #2: And the page should have a language switcher
 * Example #3: Then this page should have a HubSpot language switcher
 * Example #4: But the page should not have a language switcher
 * Example #5: Then page should not have a HubSpot language switcher
 *
 */
Then(/^(?:the |this )?page should( not)* have a (?:HubSpot )?language switcher$/, async function (notCase) {
  const ok = await poll(this, async () => ((await this.page.locator(LANGUAGE_SWITCHER).count()) > 0) === !notCase);
  if (!ok) {
    throw friendly({
      message: notCase ? 'Expected the page not to have a language switcher, but it has one.' : `Expected the page to have a language switcher (${LANGUAGE_SWITCHER}), but there is none.`,
      hint: 'The language switcher module renders `.lang_switcher_class`; a page without translations, or a theme without the module, has none.',
    });
  }
});

/**
 * The language alternates a page declares: the `hreflang` of each
 * `link[rel="alternate"]` and its address.
 *
 * @param {object} world
 * @returns {Promise<{lang: string, href: string}[]>}
 */
async function alternates(world) {
  return world.page.locator('link[rel="alternate"][hreflang]').evaluateAll((nodes) => nodes.map((n) => ({ lang: (n.getAttribute('hreflang') || '').toLowerCase(), href: n.href })));
}

/**
 * Whether a declared language is the wanted one: "de" matches "de" and "de-ch".
 *
 * @param {string} declared
 * @param {string} wanted
 * @returns {boolean}
 */
function sameLanguage(declared, wanted) {
  const w = wanted.toLowerCase();
  return declared === w || declared.startsWith(`${w}-`);
}

/**
 * Assert the page is (or is not) available in a language: the page declares an
 * alternate for it in the head (`link rel="alternate" hreflang="de"`).
 *
 * Example #1: Then the page should be available in the language "de"
 * Example #2: And the page should be available in the language "fr"
 * Example #3: Then this page should be available in the language "en"
 * Example #4: But the page should not be available in the language "ja"
 * Example #5: Then page should not be available in the language "es"
 *
 */
Then(/^(?:the |this )?page should( not)* be available in the language "([^"]*)"$/, async function (notCase, language) {
  let declared = [];
  const ok = await poll(this, async () => {
    declared = await alternates(this);
    return declared.some((a) => sameLanguage(a.lang, language)) === !notCase;
  });
  if (!ok) {
    throw friendly({
      message: notCase
        ? `Expected the page not to be available in "${language}", but it declares an alternate for it.`
        : `Expected the page to be available in "${language}", found ${declared.length ? declared.map((a) => `"${a.lang}"`).join(', ') : 'no language alternates'}.`,
      hint: 'HubSpot writes `link rel="alternate" hreflang="..."` into the head of a page that has translations; the language is the code of the alternate ("de", "fr", "pt-br").',
    });
  }
});

/**
 * Switch the page to another language: click the language switcher's link for
 * it when there is a visible one, else open the page's language alternate.
 *
 * Example #1: When I switch the language to "de"
 * Example #2: And I switch the language to "fr"
 * Example #3: When we switch the language to "de"
 * Example #4: And switch the language to "en"
 * Example #5: When I switch the language to "pt-br"
 *
 */
When(/^(I |we )*switch the language to "([^"]*)"$/, async function (pronounCase, language) {
  const code = language.toLowerCase();
  const links = this.page.locator(`.lang_switcher_class a[lang^="${code}" i], .lang_switcher_class a[hreflang^="${code}" i], .lang_list_class a[lang^="${code}" i], .lang_list_class a[hreflang^="${code}" i]`);
  const count = await links.count();
  for (let i = 0; i < count; i += 1) {
    if (await links.nth(i).isVisible().catch(() => false)) {
      await links.nth(i).click();
      await smartSettle(this.page, (this.minWaitTime && this.minWaitTime.page) || 3000);
      return;
    }
  }
  const declared = await alternates(this);
  const target = declared.find((a) => sameLanguage(a.lang, code));
  if (!target) {
    throw friendly({
      action: 'switch the language to',
      target: language,
      hint: `The page has no link for it in the language switcher and declares ${declared.length ? declared.map((a) => `"${a.lang}"`).join(', ') : 'no language alternates'}; HubSpot writes \`link rel="alternate" hreflang\` for each translation.`,
    });
  }
  await actOrExplain('switch the language to', language, () => this.page.goto(target.href, { waitUntil: 'domcontentloaded' }), 'The alternate address of the translation must be reachable.');
  await smartSettle(this.page, (this.minWaitTime && this.minWaitTime.page) || 3000);
});

/**
 * Assert the page's canonical address (`link rel="canonical"`) is the given
 * one, written as a path ("/pricing") or a full address.
 *
 * Example #1: Then the page should have the canonical address "/pricing"
 * Example #2: And the page should have the canonical address "https://example.com/blog"
 * Example #3: Then this page should have the canonical address "/"
 * Example #4: And the page should have the canonical address "/contact-us"
 * Example #5: Then page should have the canonical address "/about-us"
 *
 */
Then(/^(?:the |this )?page should have the canonical address "([^"]*)"$/, async function (expected) {
  let actual = null;
  const ok = await poll(this, async () => {
    actual = await this.page.locator('link[rel="canonical"]').first().getAttribute('href').catch(() => null);
    return sameAddress(actual, expected, this.page.url());
  });
  if (!ok) {
    throw friendly({
      message: `Expected the canonical address "${expected}", found ${actual === null ? 'no canonical link' : `"${actual}"`}.`,
      hint: 'HubSpot writes `link rel="canonical"` into the head of every page; a path such as "/pricing" matches the same path on the current site.',
    });
  }
});

/**
 * Assert the page is (or is not) hidden from search engines: HubSpot writes
 * `meta name="robots" content="noindex"` when "Hide this page from search
 * engines" is on.
 *
 * Example #1: Then the page should be hidden from search engines
 * Example #2: And the page should be hidden from search engines
 * Example #3: Then this page should be hidden from search engines
 * Example #4: But the page should not be hidden from search engines
 * Example #5: Then page should not be hidden from search engines
 *
 */
Then(/^(?:the |this )?page should( not)* be hidden from search engines$/, async function (notCase) {
  let robots = null;
  const ok = await poll(this, async () => {
    robots = await this.page.locator('meta[name="robots"]').first().getAttribute('content').catch(() => null);
    return /noindex/i.test(robots || '') === !notCase;
  });
  if (!ok) {
    throw friendly({
      message: notCase
        ? `Expected the page not to be hidden from search engines, but its robots meta tag is "${robots}".`
        : `Expected the page to be hidden from search engines (robots "noindex"), found ${robots === null ? 'no robots meta tag' : `"${robots}"`}.`,
      hint: 'HubSpot adds `<meta name="robots" content="noindex">` when "Hide this page from search engines" is set in the page\'s advanced options.',
    });
  }
});
