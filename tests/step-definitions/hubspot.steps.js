'use strict';

// Custom webship-js step definitions for testing HubSpot-built websites:
// the cookie consent banner, HubSpot forms, CTA modules, the menu module,
// and the blog listing module. Every step carries a JSDoc block with five
// Gherkin examples; tests/features/ shows them in use against demo-site/.
//
// The product word is optional in every sentence ("the HubSpot cookie
// banner" and "the cookie banner" both match), so a feature written for
// another pack reads here too. Every assertion waits for its condition (the
// assertion is the wait) for the `minWaitTime.page` budget, and every
// failure is a friendly error with a hint instead of a raw assertion or
// Playwright stack.

const { When, Then } = require('@cucumber/cucumber');
const { friendly, smartSettle } = require('webship-js/tests/step-definitions/webship');
const { budget, literal, actOrExplain } = require('./hubspot-helpers');

// The other step files.
require('./hubspot-forms.steps');
require('./hubspot-navigation.steps');
require('./hubspot-site.steps');
require('./hubspot-blog.steps');
require('./hubspot-search.steps');

const COOKIE_BANNER = '#hs-eu-cookie-confirmation';
const COOKIE_ACCEPT = '#hs-eu-confirmation-button';
const COOKIE_DECLINE = '#hs-eu-decline-button';
const CTA_BUTTON = '.hs-cta-wrapper .cta_button';

const COOKIE_HINT = 'The HubSpot cookie banner is `#hs-eu-cookie-confirmation` with `#hs-eu-confirmation-button` / `#hs-eu-decline-button`; it only shows when cookie consent is enabled for the visitor\'s region and has not been answered yet.';
const CTA_HINT = 'CTA modules render as `.hs-cta-wrapper .cta_button` and are matched by their visible label; check the wording and that the CTA is published.';

/**
 * Wait until `locator` has (or, with `notCase`, has no) visible match, then
 * throw a friendly error otherwise: the wait and the assertion are one call.
 */
async function assertPresence(locator, notCase, { label, hint, timeout }) {
  try {
    await locator.first().waitFor({ state: notCase ? 'hidden' : 'visible', timeout });
  } catch {
    throw friendly({
      message: notCase ? `Expected not to see ${label}, but it is visible.` : `Expected ${label} to be visible, but it did not appear within ${timeout} ms.`,
      hint,
    });
  }
}

/**
 * Assert that the current page was (or was not) generated by HubSpot, via
 * the `<meta name="generator" content="HubSpot">` tag HubSpot CMS pages
 * emit.
 *
 * Example #1: Then the page should be a HubSpot page
 * Example #2: And the page should be a HubSpot page
 * Example #3: Then this page should be a HubSpot page
 * Example #4: But the page should not be a HubSpot page
 * Example #5: Then page should be a HubSpot page
 *
 */
Then(/^(?:the |this )?page should( not)* be a HubSpot page$/, async function (notCase) {
  const timeout = budget(this);
  try {
    await this.page.waitForFunction((want) => {
      const meta = document.querySelector('meta[name="generator"]');
      const content = meta ? (meta.getAttribute('content') || '') : '';
      return content.toLowerCase().includes('hubspot') === want;
    }, !notCase, { timeout });
  } catch {
    const content = await this.page.locator('meta[name="generator"]').first().getAttribute('content').catch(() => null);
    throw friendly({
      message: notCase
        ? `Expected the page not to be a HubSpot page, but its generator meta tag is "${content}".`
        : `Expected a <meta name="generator" content="HubSpot"> tag, found: ${content === null ? 'no generator meta tag' : `"${content}"`}.`,
      hint: 'HubSpot CMS writes the generator meta tag into every hosted page; a page served from another host or a proxy error page will not carry it.',
    });
  }
});

/**
 * Accept the HubSpot cookie consent banner.
 *
 * Example #1: When I accept the HubSpot cookie banner
 * Example #2: And I accept the HubSpot cookie banner
 * Example #3: When we accept the cookie banner
 * Example #4: And accept the HubSpot cookie banner
 * Example #5: When I accept the cookie banner
 *
 */
When(/^(I |we )*accept the (?:HubSpot )?cookie banner$/, async function (pronounCase) {
  const button = this.page.locator(COOKIE_ACCEPT).first();
  await actOrExplain('accept the cookie banner', COOKIE_ACCEPT, async () => {
    await button.waitFor({ state: 'visible', timeout: budget(this) });
    await button.click();
  }, COOKIE_HINT);
});

/**
 * Decline the HubSpot cookie consent banner.
 *
 * Example #1: When I decline the HubSpot cookie banner
 * Example #2: And I decline the HubSpot cookie banner
 * Example #3: When we decline the cookie banner
 * Example #4: And decline the HubSpot cookie banner
 * Example #5: When I decline the cookie banner
 *
 */
When(/^(I |we )*decline the (?:HubSpot )?cookie banner$/, async function (pronounCase) {
  const button = this.page.locator(COOKIE_DECLINE).first();
  await actOrExplain('decline the cookie banner', COOKIE_DECLINE, async () => {
    await button.waitFor({ state: 'visible', timeout: budget(this) });
    await button.click();
  }, COOKIE_HINT);
});

/**
 * Assert the HubSpot cookie banner is (or is not) visible. The negative
 * form passes when the banner was dismissed or is absent.
 *
 * Example #1: Then the HubSpot cookie banner should be visible
 * Example #2: Then the HubSpot cookie banner should not be visible
 * Example #3: And the cookie banner should be visible
 * Example #4: But the cookie banner should not be visible
 * Example #5: Then I should see the HubSpot cookie banner
 *
 */
Then(/^(?:(?:the )?(?:HubSpot )?cookie banner should( not)* be visible|(?:I |we )*should( not)* see the (?:HubSpot )?cookie banner)$/, async function (notVisible, notSee) {
  await assertPresence(this.page.locator(COOKIE_BANNER), notVisible || notSee, {
    label: 'the HubSpot cookie banner',
    hint: COOKIE_HINT,
    timeout: budget(this),
  });
});
