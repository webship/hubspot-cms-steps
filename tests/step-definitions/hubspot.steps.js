'use strict';

// Custom webship-js step definitions for testing HubSpot-built websites:
// the cookie consent banner, HubSpot forms, CTA modules, the menu module,
// and the blog listing module. See docs/step-reference.md for the full
// catalogue and examples/ for sample .feature usage.

const { Given, When, Then } = require('@cucumber/cucumber');
const assert = require('assert');
const { friendly } = require('webship-js/tests/step-definitions/webship');

const COOKIE_BANNER = '#hs-eu-cookie-confirmation';
const COOKIE_ACCEPT = '#hs-eu-confirmation-button';
const COOKIE_DECLINE = '#hs-eu-decline-button';
const FORM_FRAME = '.hs-form-frame';
const SUCCESS_MESSAGE = '.hs-form-frame .submitted-message';

/**
 * Assert that the current page was generated by HubSpot, via the
 * `<meta name="generator" content="HubSpot">` tag HubSpot CMS pages emit.
 *
 * Example #1: Then the page should be a HubSpot page
 * Example #2: Given I am on "/index.html"
 *               Then the page should be a HubSpot page
 * Example #3: Given I am on "/pricing.html"
 *               Then the page should be a HubSpot page
 * Example #4: Given I am on "/blog/index.html"
 *               Then the page should be a HubSpot page
 * Example #5: And the page should be a HubSpot page
 *
 */
Then('the page should be a HubSpot page', async function () {
  const content = await this.page.locator('meta[name="generator"]').first().getAttribute('content');
  assert.ok(
    content && content.toLowerCase().includes('hubspot'),
    `Expected a <meta name="generator" content="HubSpot"> tag, found: "${content}".`
  );
});

/**
 * Accept the HubSpot cookie consent banner.
 *
 * Example #1: Given I accept the HubSpot cookie banner
 * Example #2: When I accept the HubSpot cookie banner
 * Example #3: Given I am on "/index.html"
 *               And I accept the HubSpot cookie banner
 * Example #4: Given I am on "/contact-us.html"
 *               And I accept the HubSpot cookie banner
 * Example #5: When we accept the HubSpot cookie banner
 *
 */
Given(/^(I |we )*accept the HubSpot cookie banner$/, async function (pronounCase) {
  try {
    await this.page.locator(COOKIE_ACCEPT).click();
  } catch (err) {
    throw friendly({ action: 'accept the HubSpot cookie banner', target: COOKIE_ACCEPT, cause: err });
  }
});

/**
 * Decline the HubSpot cookie consent banner.
 *
 * Example #1: Given I decline the HubSpot cookie banner
 * Example #2: When I decline the HubSpot cookie banner
 * Example #3: Given I am on "/index.html"
 *               And I decline the HubSpot cookie banner
 * Example #4: When we decline the HubSpot cookie banner
 * Example #5: And I decline the HubSpot cookie banner
 *
 */
Given(/^(I |we )*decline the HubSpot cookie banner$/, async function (pronounCase) {
  try {
    await this.page.locator(COOKIE_DECLINE).click();
  } catch (err) {
    throw friendly({ action: 'decline the HubSpot cookie banner', target: COOKIE_DECLINE, cause: err });
  }
});

/**
 * Assert the HubSpot cookie banner is currently visible.
 *
 * Example #1: Then the HubSpot cookie banner should be visible
 * Example #2: Given I am on "/index.html"
 *               Then the HubSpot cookie banner should be visible
 * Example #3: Given I am on "/pricing.html"
 *               Then the HubSpot cookie banner should be visible
 * Example #4: And the HubSpot cookie banner should be visible
 * Example #5: Given I am on "/blog/index.html"
 *               Then the HubSpot cookie banner should be visible
 *
 */
Then('the HubSpot cookie banner should be visible', async function () {
  await assert.ok(await this.page.locator(COOKIE_BANNER).isVisible(), 'Expected the HubSpot cookie banner to be visible.');
});

/**
 * Assert the HubSpot cookie banner is not visible (dismissed or absent).
 *
 * Example #1: Then the HubSpot cookie banner should not be visible
 * Example #2: Given I accept the HubSpot cookie banner
 *               Then the HubSpot cookie banner should not be visible
 * Example #3: Given I decline the HubSpot cookie banner
 *               Then the HubSpot cookie banner should not be visible
 * Example #4: And the HubSpot cookie banner should not be visible
 * Example #5: When I accept the HubSpot cookie banner
 *               Then the HubSpot cookie banner should not be visible
 *
 */
Then('the HubSpot cookie banner should not be visible', async function () {
  const visible = await this.page.locator(COOKIE_BANNER).isVisible().catch(() => false);
  assert.ok(!visible, 'Expected the HubSpot cookie banner to be hidden.');
});

/**
 * Fill a field, located by its name attribute or label, inside the
 * page's HubSpot form.
 *
 * Example #1: When I fill in the HubSpot form field "email" with "jane@example.com"
 * Example #2: When I fill in the HubSpot form field "firstname" with "Jane"
 * Example #3: And I fill in the HubSpot form field "lastname" with "Doe"
 * Example #4: And I fill in the HubSpot form field "message" with "Please call me back"
 * Example #5: When we fill in the HubSpot form field "email" with "test@acme.com"
 *
 */
When(/^(I |we )*fill in the HubSpot form field "([^"]*)?" with "([^"]*)?"$/, async function (pronounCase, field, value) {
  const locator = this.page.locator(`${FORM_FRAME} [name="${field}"]`).first();
  try {
    await locator.fill(value);
  } catch (err) {
    throw friendly({ action: 'fill in the HubSpot form field', target: field, cause: err });
  }
});

/**
 * Submit the page's HubSpot form.
 *
 * Example #1: When I submit the HubSpot form
 * Example #2: And I submit the HubSpot form
 * Example #3: When we submit the HubSpot form
 * Example #4: Given I fill in the HubSpot form field "email" with "jane@example.com"
 *               When I submit the HubSpot form
 * Example #5: And I submit the HubSpot form
 *
 */
When(/^(I |we )*submit the HubSpot form$/, async function (pronounCase) {
  try {
    await this.page.locator(`${FORM_FRAME} [type="submit"]`).first().click();
  } catch (err) {
    throw friendly({ action: 'submit the HubSpot form', cause: err });
  }
});

/**
 * Assert the HubSpot form's success ("thank you") message is visible.
 *
 * Example #1: Then the HubSpot form should show a success message
 * Example #2: When I submit the HubSpot form
 *               Then the HubSpot form should show a success message
 * Example #3: And the HubSpot form should show a success message
 * Example #4: When we submit the HubSpot form
 *               Then the HubSpot form should show a success message
 * Example #5: Then the HubSpot form should show a success message
 *
 */
Then('the HubSpot form should show a success message', async function () {
  assert.ok(
    await this.page.locator(SUCCESS_MESSAGE).isVisible(),
    'Expected the HubSpot form to show a success message after submission.'
  );
});

/**
 * Assert the HubSpot form's success message contains the given text.
 *
 * Example #1: Then the HubSpot form should show a success message containing "Thanks"
 * Example #2: Then the HubSpot form should show a success message containing "in touch"
 * Example #3: And the HubSpot form should show a success message containing "received your message"
 * Example #4: Then the HubSpot form should show a success message containing "shortly"
 * Example #5: When I submit the HubSpot form
 *               Then the HubSpot form should show a success message containing "Thanks"
 *
 */
Then('the HubSpot form should show a success message containing {string}', async function (text) {
  const content = await this.page.locator(SUCCESS_MESSAGE).textContent();
  assert.ok(
    content && content.includes(text),
    `Expected the HubSpot form success message to contain "${text}", found: "${content}".`
  );
});

/**
 * Click a HubSpot CTA module button/link identified by its visible label.
 *
 * Example #1: When I click the HubSpot CTA "See Pricing"
 * Example #2: When I click the HubSpot CTA "Talk to Sales"
 * Example #3: And I click the HubSpot CTA "Get Started"
 * Example #4: When we click the HubSpot CTA "Start Free Trial"
 * Example #5: And I click the HubSpot CTA "Get in Touch"
 *
 */
When(/^(I |we )*click the HubSpot CTA "([^"]*)?"$/, async function (pronounCase, label) {
  const locator = this.page.locator('.hs-cta-wrapper .cta_button', { hasText: label }).first();
  try {
    await locator.click();
  } catch (err) {
    throw friendly({ action: 'click the HubSpot CTA', target: label, cause: err });
  }
});

/**
 * Assert a HubSpot CTA module button/link points at the given href.
 *
 * Example #1: Then the HubSpot CTA "See Pricing" should link to "/pricing.html"
 * Example #2: Then the HubSpot CTA "Talk to Sales" should link to "/contact-us.html"
 * Example #3: And the HubSpot CTA "Get Started" should link to "/contact-us.html"
 * Example #4: Then the HubSpot CTA "Get in Touch" should link to "/contact-us.html"
 * Example #5: Then the HubSpot CTA "Start Free Trial" should link to "/contact-us.html"
 *
 */
Then('the HubSpot CTA {string} should link to {string}', async function (label, href) {
  const locator = this.page.locator('.hs-cta-wrapper .cta_button', { hasText: label }).first();
  const actual = await locator.getAttribute('href');
  assert.strictEqual(actual, href, `Expected the "${label}" CTA to link to "${href}", found "${actual}".`);
});

/**
 * Assert the HubSpot menu module has a link with the given label.
 *
 * Example #1: Then the HubSpot menu should have a link labeled "Pricing"
 * Example #2: Then the HubSpot menu should have a link labeled "Blog"
 * Example #3: And the HubSpot menu should have a link labeled "Contact"
 * Example #4: Then the HubSpot menu should have a link labeled "About"
 * Example #5: Then the HubSpot menu should have a link labeled "Home"
 *
 */
Then('the HubSpot menu should have a link labeled {string}', async function (label) {
  const count = await this.page.locator('.hs-menu-wrapper a', { hasText: label }).count();
  assert.ok(count > 0, `Expected the HubSpot menu to have a link labeled "${label}".`);
});

/**
 * Assert the HubSpot blog listing module shows at least N posts.
 *
 * Example #1: Then the HubSpot blog should list at least 1 posts
 * Example #2: Then the HubSpot blog should list at least 3 posts
 * Example #3: Given I am on "/blog/index.html"
 *               Then the HubSpot blog should list at least 2 posts
 * Example #4: And the HubSpot blog should list at least 3 posts
 * Example #5: Then the HubSpot blog should list at least 1 posts
 *
 */
Then('the HubSpot blog should list at least {int} posts', async function (minimum) {
  const count = await this.page.locator('.hs-blog-post-listing .hs-blog-post').count();
  assert.ok(count >= minimum, `Expected at least ${minimum} blog posts, found ${count}.`);
});

