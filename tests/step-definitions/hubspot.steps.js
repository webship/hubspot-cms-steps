/**
 * Assert the HubSpot cookie banner is (or is not) visible. The negative
 * form passes when the banner was dismissed or is absent.
 *
 * Example #1: Then the HubSpot cookie banner should be visible
 * Example #2: Then the HubSpot cookie banner should not be visible
 * Example #3: And the cookie banner should be visible
 * Example #4: But the cookie banner should not be visible
 * Example #5: Then I should see the HubSpot cookie banner
 *
 */
Then(/^(?:(?:the )?(?:HubSpot )?cookie banner should( not)* be visible|(?:I |we )*should( not)* see the (?:HubSpot )?cookie banner)$/, async function (notVisible, notSee) {
  await assertPresence(this.page.locator(COOKIE_BANNER), notVisible || notSee, {
    label: 'the HubSpot cookie banner',
    hint: COOKIE_HINT,
    timeout: budget(this),
  });
});

/**
 * Fill a field, located by its name attribute, inside the page's HubSpot
 * form.
 *
 * Example #1: When I fill in the HubSpot form field "email" with "jane@example.com"
 * Example #2: When I fill in the HubSpot form field "firstname" with "Jane"
 * Example #3: And I fill in the form field "lastname" with "Doe"
 * Example #4: And fill in the HubSpot form field "message" with "Please call me back"
 * Example #5: When we fill in the form field "email" with "test@acme.com"
 *
 */
When(/^(I |we )*fill in the (?:HubSpot )?form field "([^"]*)?" with "([^"]*)?"$/, async function (pronounCase, field, value) {
  const locator = this.page.locator(`${FORM_FRAME} [name="${field}"]`).first();
  await actOrExplain('fill in the form field', field, async () => {
    await locator.waitFor({ state: 'visible', timeout: budget(this) });
    await locator.fill(value);
  }, FORM_HINT);
});

/**
 * Submit the page's HubSpot form and wait for the page to settle, so the
 * AJAX response has a chance to replace the form with its message.
 *
 * Example #1: When I submit the HubSpot form
 * Example #2: And I submit the HubSpot form
 * Example #3: When we submit the form
 * Example #4: And submit the HubSpot form
 * Example #5: When I submit the form
 *
 */
When(/^(I |we )*submit the (?:HubSpot )?form$/, async function (pronounCase) {
  const submit = this.page.locator(`${FORM_FRAME} [type="submit"]`).first();
  await actOrExplain('submit the form', FORM_FRAME, async () => {
    await submit.waitFor({ state: 'visible', timeout: budget(this) });
    await submit.click();
  }, FORM_HINT + ' The submit button is the form\'s `[type="submit"]`.');
  await smartSettle(this.page, (this.minWaitTime && this.minWaitTime.page) || 3000);
});

/**
 * Assert the HubSpot form's success ("thank you") message is (or is not)
 * visible, optionally containing the given text.
 *
 * Example #1: Then the HubSpot form should show a success message
 * Example #2: Then the HubSpot form should show a success message containing "Thanks"
 * Example #3: And the form should show a success message containing "received your message"
 * Example #4: But the HubSpot form should not show a success message
 * Example #5: Then the form should not show a success message containing "error"
 *
 */
Then(/^(?:the )?(?:HubSpot )?form should( not)* show a success message(?: containing "([^"]*)?")?$/, async function (notCase, text) {
  let message = this.page.locator(SUCCESS_MESSAGE);
  if (text) message = message.filter({ hasText: literal(text) });
  const timeout = budget(this);
  try {
    await message.first().waitFor({ state: notCase ? 'hidden' : 'visible', timeout });
  } catch {
    const content = (await this.page.locator(SUCCESS_MESSAGE).first().textContent().catch(() => null) || '').trim();
    throw friendly({
      message: notCase
        ? `Expected the form not to show a success message${text ? ` containing "${text}"` : ''}, but it does ("${content}").`
        : `Expected the form to show a success message${text ? ` containing "${text}"` : ''} within ${timeout} ms${content ? `, found: "${content}"` : ', but none appeared'}.`,
      hint: 'HubSpot replaces the form with `.submitted-message` after a successful AJAX submit; submit the form first and check the form\'s thank-you text (the match is case-sensitive).',
    });
  }
});

/**
 * Click a HubSpot CTA module button/link identified by its visible label.
 *
 * Example #1: When I click the HubSpot CTA "See Pricing"
 * Example #2: When I click the HubSpot CTA "Talk to Sales"
 * Example #3: And I click the CTA "Get Started"
 * Example #4: When we click the HubSpot CTA "Start Free Trial"
 * Example #5: And click the CTA "Get in Touch"
 *
 */
When(/^(I |we )*click the (?:HubSpot )?CTA "([^"]*)?"$/, async function (pronounCase, label) {
  const locator = this.page.locator(CTA_BUTTON, { hasText: label }).first();
  await actOrExplain('click the CTA', label, async () => {
    await locator.waitFor({ state: 'visible', timeout: budget(this) });
    await locator.click();
  }, CTA_HINT);
  await smartSettle(this.page, (this.minWaitTime && this.minWaitTime.page) || 3000);
});

/**
 * Assert a HubSpot CTA module button/link does (or does not) point at the
 * given href.
 *
 * Example #1: Then the HubSpot CTA "See Pricing" should link to "/pricing.html"
 * Example #2: Then the HubSpot CTA "Talk to Sales" should link to "/contact-us.html"
 * Example #3: And the CTA "Get Started" should link to "/contact-us.html"
 * Example #4: But the HubSpot CTA "Get in Touch" should not link to "/pricing.html"
 * Example #5: Then CTA "Start Free Trial" should link to "/contact-us.html"
 *
 */
Then(/^(?:the )?(?:HubSpot )?CTA "([^"]*)?" should( not)* link to "([^"]*)?"$/, async function (label, notCase, href) {
  const locator = this.page.locator(CTA_BUTTON, { hasText: label }).first();
  const timeout = budget(this);
  await actOrExplain('find the CTA', label, () => locator.waitFor({ state: 'attached', timeout }), CTA_HINT);
  try {
    await this.page.waitForFunction(
      ({ sel, text, want, expected }) => {
        const el = Array.from(document.querySelectorAll(sel)).find((a) => (a.textContent || '').includes(text));
        return Boolean(el) && (el.getAttribute('href') === expected) === want;
      },
      { sel: CTA_BUTTON, text: label, want: !notCase, expected: href },
      { timeout }
    );
  } catch {
    const actual = await locator.getAttribute('href').catch(() => null);
    throw friendly({
      message: notCase
        ? `Expected the "${label}" CTA not to link to "${href}", but it does.`
        : `Expected the "${label}" CTA to link to "${href}", found "${actual}".`,
      hint: 'The href is compared exactly as written in the markup (relative or absolute); check the CTA\'s destination URL in HubSpot.',
    });
  }
});

/**
 * Assert the HubSpot menu module has (or has no) link with the given label.
 *
 * Example #1: Then the HubSpot menu should have a link labeled "Pricing"
 * Example #2: Then the HubSpot menu should have a link labeled "Blog"
 * Example #3: And the menu should have a link labeled "Contact"
 * Example #4: But the HubSpot menu should not have a link labeled "Checkout"
 * Example #5: Then menu should have a link labelled "Home"
 *
 */
Then(/^(?:the )?(?:HubSpot )?menu should( not)* have a link labell?ed "([^"]*)?"$/, async function (notCase, label) {
  const timeout = budget(this);
  const link = this.page.locator('.hs-menu-wrapper a', { hasText: label });
  try {
    await link.first().waitFor({ state: notCase ? 'detached' : 'attached', timeout });
  } catch {
    throw friendly({
      message: notCase
        ? `Expected the menu not to have a link labeled "${label}", but it does.`
        : `Expected the menu to have a link labeled "${label}" within ${timeout} ms, but none appeared.`,
      hint: 'Menu modules render inside `.hs-menu-wrapper`; links are matched by their visible text, so check the label in the HubSpot menu settings.',
    });
  }
});

/**
 * Assert the HubSpot blog listing module shows at least N posts. The count
 * is polled for the wait budget, so a listing that is still rendering is
 * waited for.
 *
 * Example #1: Then the HubSpot blog should list at least 1 post
 * Example #2: Then the HubSpot blog should list at least 3 posts
 * Example #3: And the blog should list at least 2 posts
 * Example #4: Then blog should list at least 3 posts
 * Example #5: Then the HubSpot blog should list at least 1 posts
 *
 */
Then(/^(?:the )?(?:HubSpot )?blog should list at least (\d+) posts?$/, async function (minimumStr) {
  const minimum = Number(minimumStr);
  const selector = '.hs-blog-post-listing .hs-blog-post';
  const timeout = budget(this);
  try {
    await this.page.waitForFunction(({ sel, n }) => document.querySelectorAll(sel).length >= n, { sel: selector, n: minimum }, { timeout });
  } catch {
    const count = await this.page.locator(selector).count();
    throw friendly({
      message: `Expected at least ${minimum} blog post(s) in the listing, found ${count}.`,
      hint: 'The blog listing module renders `.hs-blog-post` items inside `.hs-blog-post-listing`; check the listing page URL and that enough posts are published.',
    });
  }
});

/**
 * Open a HubSpot blog post from the listing page by its title.
 *
 * Example #1: When I open the HubSpot blog post titled "Why BDD testing matters for marketing sites"
 * Example #2: When I open the HubSpot blog post titled "5 tips for testing a HubSpot CMS site"
 * Example #3: And I open the blog post titled "Automating website QA with webship-js"
 * Example #4: When we open the HubSpot blog post titled "5 tips for testing a HubSpot CMS site"
 * Example #5: And open the blog post titled "Why BDD testing matters for marketing sites"
 *
 */
When(/^(I |we )*open the (?:HubSpot )?blog post titled "([^"]*)?"$/, async function (pronounCase, title) {
  const locator = this.page.locator('.hs-blog-post-listing .hs-blog-post a', { hasText: title }).first();
  await actOrExplain('open the blog post', title, async () => {
    await locator.waitFor({ state: 'visible', timeout: budget(this) });
    await locator.click();
  }, 'Blog post links are matched by their visible title inside the listing (`.hs-blog-post a`); open the blog listing page first and check the title text.');
  await smartSettle(this.page, (this.minWaitTime && this.minWaitTime.page) || 3000);
});
